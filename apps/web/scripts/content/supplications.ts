// The Supplications' tables and their first load (#199, ADR 0027, ADR 0015).
// The curated file (data/supplications/supplications.json, built once by
// scripts/curate-supplications.ts) is this data migration's frozen input: it
// is read only here, once per database, and from then on the
// "supplication_speaker" and "supplication" tables are the only place the
// Speakers and Supplications are kept or changed. The website reads them
// through src/supplications/. The tables are described in ADR 0043.

import fs from "node:fs";
import { fileURLToPath } from "node:url";
import type { PoolClient } from "pg";
import { auditTable } from "./content-audit.ts";

const CURATED = fileURLToPath(new URL("../../data/supplications/supplications.json", import.meta.url));
/**
 * QUL's Surah metadata, for each Surah's Ayah count: a source kept in the repo
 * for good (ADR 0011), and this migration is run on every new database.
 */
const SURAHS = fileURLToPath(new URL("../../data/qul/quran-metadata-surah-name.json", import.meta.url));

/** Each Surah's Ayah count, in Surah order, as a Postgres array literal. */
function ayahCounts(): string {
  const surahs = Object.values(JSON.parse(fs.readFileSync(SURAHS, "utf8")) as Record<string, { id: number; verses_count: number }>);
  return `array[${surahs.toSorted((a, b) => a.id - b.id).map((s) => Number(s.verses_count)).join(",")}]::smallint[]`;
}

/**
 * The Speakers, by slug, each named in English and Urdu with its Prophet mark;
 * and the Supplications and Other words to Allah, each a run of Ayahs within
 * one Surah said by one Speaker, with its Openings (a non-empty set, written
 * rabbana, rabbi, other) and kind. Each row has a version a later save will
 * raise. The checks hold every row, an Admin's edits included, to a run within
 * its Surah's Ayahs, and the exclusion to no Ayah in two runs: a run is a range
 * of Surah × 1000 + Ayah, as no Surah has 1000 Ayahs. Both tables are each
 * audited in `content_audit` (ADR 0038), from their creation.
 */
export async function createSupplicationTables(client: PoolClient) {
  await client.query(`
    create table supplication_speaker (
      id text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
      name_en text not null check (name_en <> ''),
      name_ur text not null check (name_ur <> ''),
      includes_prophet boolean not null,
      version integer not null default 1
    )`);
  await client.query(`
    create table supplication (
      id integer generated by default as identity primary key,
      surah smallint not null check (surah between 1 and 114),
      ayah_from smallint not null check (ayah_from >= 1),
      ayah_to smallint not null,
      speaker_id text not null references supplication_speaker (id),
      openings text[] not null check (cardinality(openings) > 0 and openings <@ array['rabbana', 'rabbi', 'other']),
      kind text not null check (kind in ('supplication', 'plea-at-the-judgment', 'request-for-this-world-only',
                                         'complaint', 'mockery', 'hypothetical', 'reported-words')),
      version integer not null default 1,
      check (ayah_from <= ayah_to),
      check (ayah_to <= (${ayahCounts()})[surah]),
      exclude using gist (int4range(surah * 1000 + ayah_from, surah * 1000 + ayah_to, '[]') with &&)
    )`);
  for (const table of ["supplication_speaker", "supplication"]) await auditTable(client, table);
}

interface Curated {
  speakers: { id: string; nameEn: string; nameUr: string; includesProphet: boolean }[];
  supplications: { surah: number; ayahFrom: number; ayahTo: number; speakerId: string; openings: string[]; kind: string }[];
}

/** Load the curated file's Speakers and Supplications, each at version 1; the Supplications' ids follow Quran order, from 1. */
export async function loadSupplications(client: PoolClient) {
  const { speakers, supplications } = JSON.parse(fs.readFileSync(CURATED, "utf8")) as Curated;
  await client.query(
    `insert into supplication_speaker (id, name_en, name_ur, includes_prophet)
     select id, "nameEn", "nameUr", "includesProphet"
       from jsonb_to_recordset($1::jsonb) as r(id text, "nameEn" text, "nameUr" text, "includesProphet" boolean)`,
    [JSON.stringify(speakers)],
  );
  await client.query(
    `insert into supplication (surah, ayah_from, ayah_to, speaker_id, openings, kind)
     select surah, "ayahFrom", "ayahTo", "speakerId", array(select jsonb_array_elements_text(openings)), kind
       from jsonb_to_recordset($1::jsonb) as r(surah smallint, "ayahFrom" smallint, "ayahTo" smallint, "speakerId" text,
            openings jsonb, kind text)
      order by surah, "ayahFrom"`,
    [JSON.stringify(supplications)],
  );
}
